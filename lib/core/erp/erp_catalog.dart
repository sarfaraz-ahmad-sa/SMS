  static ErpModule? byId(String id) {
    for (final module in modules) {
      if (module.id == id) return module;
    }
    return null;
  }

  static ErpEntity? entityByCollection(String collection) {
    for (final module in modules) {
      for (final entity in module.entities) {
        if (entity.collection == collection) return entity;
      }
    }
    return null;
  }

  static ErpModule? moduleForCollection(String collection) {
    for (final module in modules) {
      if (module.entities.any(
        (ErpEntity entity) => entity.collection == collection,
      )) {
        return module;
      }
    }
    return null;
  }

